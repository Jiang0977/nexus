// Keep native checkpoints on the same width table as the pinned browser xterm.
// Prints Rust source; --check compares the committed table without editing it.
import { readFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { runInNewContext } from 'node:vm'
const require = createRequire(new URL('../frontend/package.json', import.meta.url))
const ts = require('typescript')
const source = readFileSync(new URL('../frontend/node_modules/@xterm/addon-unicode11/src/UnicodeV11.ts', import.meta.url), 'utf8')
const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText
const exports = {}
runInNewContext(js, { exports, require: () => ({}) })
const provider = new exports.UnicodeV11()
const ranges = []
for (let cp = 0; cp <= 0x10ffff;) {
  const width = provider.wcwidth(cp), start = cp++
  while (cp <= 0x10ffff && provider.wcwidth(cp) === width) cp++
  if (width !== 1) ranges.push(`    (0x${start.toString(16)}, 0x${(cp - 1).toString(16)}, ${width}),`)
}
const result = `// Generated by scripts/generate-native-unicode-width.mjs from addon-unicode11 0.9.0.\n// Copyright (c) The xterm.js authors. MIT; see XTERM-LICENSE.\npub(crate) fn char_width(ch: char) -> u8 {\n    let cp = ch as u32;\n    let index = RANGES.partition_point(|range| range.1 < cp);\n    RANGES.get(index).filter(|range| range.0 <= cp).map_or(1, |range| range.2)\n}\n\nconst RANGES: &[(u32, u32, u8)] = &[\n${ranges.join('\n')}\n];\n`
if (process.argv.includes('--check')) {
  const committed = readFileSync(new URL('../rust-runtime/vendor/avt/src/width.rs', import.meta.url), 'utf8')
  if (committed.replace(/\s/g, '') !== result.replace(/\s/g, '')) throw new Error('Native Unicode width table differs from browser xterm; regenerate it')
} else process.stdout.write(result)
